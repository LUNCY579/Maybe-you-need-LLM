import { useMemo } from 'react'
import { fmt } from '@llm-materials/course-core'
import { COMPANION_MODEL, companionFigures } from '../../core/companions'
import { Callout, DataTable, Figure, Panel, Stat } from '@llm-materials/course-ui'

export function CompanionsLab() {
  const figures = useMemo(() => companionFigures(), [])
  const first = figures[0]!
  const last = figures[figures.length - 1]!
  const distinct = new Set(figures.map((figure) => figure.unit)).size

  return (
    <div className="lab">
      <Panel
        title="Laboratory I · The companion figures"
        subtitle="One computed number for every lecture, from the same functions the laboratories use"
        accent="indigo"
      >
        <div className="stat-row">
          <Stat label="The figures" value={String(figures.length)} hint="one per lecture" />
          <Stat label="The units" value={String(distinct)} hint="distinct kinds of quantity" />
          <Stat label="The first" value={`${fmt(first.value, first.decimals)}`} hint={first.unit} />
          <Stat label="The last" value={`${fmt(last.value, last.decimals)}`} hint={last.unit} />
        </div>

        <Figure
          title="Every lecture, and the number that accompanies it"
          description="The figure each lesson links to, computed on demand from the course’s own pure functions."
          caption="The model is fixed at a 768-wide, 12-layer, 32,000-token vocabulary model, except where the lesson is about the size itself. The corpus is generated by the course’s own code, with a seed. Nothing in this table is stored or typed in: every value is recomputed when the page is opened, and a test checks each one."
        >
          <DataTable
            caption="The companion figures"
            headers={['Lesson', 'The figure', 'Value', 'What it supports']}
            rows={figures.map((figure) => [
              `${figure.lessonNumber} · ${figure.title}`,
              figure.label,
              `${fmt(figure.value, figure.decimals)} ${figure.unit}`,
              figure.sentence,
            ])}
          />
        </Figure>

        <Callout tone="definition" title="What makes a figure a companion">
          A lecture’s figure is a companion when it is derived from the lecture’s own arithmetic, not from a picture of
          it. The bytes per token come from training a byte-pair encoding; the parameter shares come from counting the
          matrices; the FLOPs come from the shapes; the loss at initialisation is the logarithm of the vocabulary; the
          scaling point is the compute-optimal allocation at 1e23 FLOPs. Each is a number this course computed, and each
          is what its lecture is actually about.
        </Callout>

        <Callout tone="note" title="The reference model">
          {`The shared model is ${COMPANION_MODEL.layers} layers of width ${COMPANION_MODEL.dModel}, ${COMPANION_MODEL.heads} heads, a feed-forward width of ${COMPANION_MODEL.dFf}, a ${COMPANION_MODEL.contextLength.toLocaleString()}-token context and a ${COMPANION_MODEL.vocabSize.toLocaleString()}-token vocabulary. The lessons that are about the tokeniser or the data pipeline compute their own corpus instead, and the scaling lesson uses the published exponents.`}
        </Callout>
      </Panel>
    </div>
  )
}
