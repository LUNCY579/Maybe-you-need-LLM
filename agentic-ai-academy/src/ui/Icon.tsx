/**
 * Inline icons.
 *
 * Every icon is a decorative SVG marked `aria-hidden`. Using an SVG rather
 * than a unicode glyph matters for two reasons: the glyph renders
 * inconsistently across platforms, and — more importantly — an SVG is not
 * *text*, so it does not take part in the WCAG 2.5.3 "Label in Name" check
 * that requires an accessible name to contain the element's visible text.
 */

export interface IconProps {
  className?: string
  /** Accessible name. Leave undefined for decorative icons. */
  title?: string
}

function Svg({ children, className, title }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      width="1em"
      height="1em"
      aria-hidden={title ? undefined : 'true'}
      role={title ? 'img' : undefined}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  )
}

